/** Lee todos los registros de una tabla de IndexedDB. */
const readStore = (page, dbName, store) => page.evaluate(async ({ dbName, store }) => {
  const db = await new Promise((res, rej) => { const r = indexedDB.open(dbName); r.onsuccess = () => res(r.result); r.onerror = () => rej(r.error) })
  const rows = await new Promise((res, rej) => { const r = db.transaction(store).objectStore(store).getAll(); r.onsuccess = () => res(r.result); r.onerror = () => rej(r.error) })
  db.close()
  return rows
}, { dbName, store })

